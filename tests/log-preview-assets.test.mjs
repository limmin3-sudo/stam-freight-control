import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,copyFile,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
test('optional 3D download rejects invalid and oversized payloads without caching them',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'stam-preview-assets-'));
 t.after(()=>rm(dir,{recursive:true,force:true}));
 await mkdir(join(dir,'integration/log'),{recursive:true});
 const file=join(dir,'integration/log/preview-assets-node.mjs');
 await copyFile(new URL('../integration/log/preview-assets-node.mjs',import.meta.url),file);
 const {preparePreviewAssets}=await import(pathToFileURL(file));
 const original=globalThis.fetch;t.after(()=>{globalThis.fetch=original;});
 globalThis.fetch=async()=>new Response('invalid-library');
 await assert.rejects(preparePreviewAssets(),/integrity/);
 globalThis.fetch=async()=>new Response(new Uint8Array(3*1024*1024+1));
 await assert.rejects(preparePreviewAssets(),/too-large/);
 await assert.rejects(readFile(join(dir,'vendor/three.module.js')),/ENOENT/);
});
