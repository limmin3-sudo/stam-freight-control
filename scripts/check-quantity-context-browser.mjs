import assert from 'node:assert/strict';
import {pathToFileURL,fileURLToPath} from 'node:url';
const {chromium}=await import(pathToFileURL(process.env.STAM_PLAYWRIGHT_MODULE||'/opt/codex/runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs'));
const base=process.env.STAM_MISSION_URL||'http://127.0.0.1:5186/';
const browser=await chromium.launch({executablePath:process.env.STAM_CHROMIUM||'/usr/bin/chromium',args:['--no-sandbox','--enable-unsafe-swiftshader']});
const key='stam.control-room.flight.v1';
try {
 const page=await browser.newPage({viewport:{width:1366,height:900},deviceScaleFactor:.5,reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'#/mission?lang=ko');
 await page.getByLabel('운항 파트너',{exact:true}).selectOption('navigator');
 await page.getByText('계약 백업 · 불러오기',{exact:true}).click();
 await page.locator('input[type=file][accept=".json,application/json"]').setInputFiles(fileURLToPath(new URL('../docs/function-review-20261112/pooled-reservation.json',import.meta.url)));
 await page.locator('.dispatch-launch').click();
 await page.waitForSelector('.chart-stop-events');
 assert.match(await page.locator('.chart-stops').innerText(),/최대치 기준 · 실제 수량 미확인/);
 await page.evaluate(()=>location.hash='#/mission?lang=ko');
 await page.locator('.quick-totals input').fill('22');
 await page.locator('.dispatch-launch').click();
 await page.waitForFunction(key=>JSON.parse(localStorage.getItem(key))?.plan?.peak===22,key);
 await page.waitForSelector('.chart-stop-events');
 assert.match(await page.locator('.chart-stops').innerText(),/총량 확인 · 상자 예상/);
 assert.doesNotMatch(await page.locator('.chart-stops').innerText(),/최대치 기준/);
 await page.evaluate(()=>location.hash='#/operations?lang=ko');
 await page.getByRole('button',{name:'운항 시작',exact:true}).click();
 await page.getByRole('button',{name:/^출발 완료/}).click();
 const instructions=await page.locator('.ops-tasks').innerText();
 assert.match(instructions,/수량 미확인/,'per-pickup shares stay unknown');
 assert.match(instructions,/배송 총량 · 22 SCU/,'only the confirmed delivery total is reserved');
 assert.match(instructions,/총량 확인 · 상자 예상/);
 assert.doesNotMatch(instructions,/32 SCU|최대치 기준/);
 await page.getByRole('button',{name:/^접수 완료/}).click();
 const state=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),key);
 assert.equal(state.run.aboard.reduce((sum,b)=>sum+b.size,0),22);
 assert(state.run.aboard.every(b=>b._reservation),'reserved boxes are not promoted to actual pickup quantities');
 assert.deepEqual(state.draft.jobs[0].shipments.map(s=>s.scu),[0,0]);
 assert.deepEqual(errors,[]);
 console.log('PASS: upper-bound labels change to confirmed delivery total across map/operations; 22 SCU reserved once, pickup shares remain unknown');
}finally{await browser.close();}
