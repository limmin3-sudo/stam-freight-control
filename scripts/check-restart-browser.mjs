import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdtemp,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';import {join} from 'node:path';
import {startLogService} from '../integration/log/live-server.mjs';
import {data} from '../tests/helpers/log-preview.mjs';
const {chromium}=createRequire(import.meta.url)(process.env.STAM_PLAYWRIGHT_MODULE||'playwright');
const dir=await mkdtemp(join(tmpdir(),'stam-restart-')),file=join(dir,'synthetic.log');await writeFile(file,'');
let service=await startLogService({file}),browser;
try{
 browser=await chromium.launch({...(process.env.STAM_CHROMIUM_PATH?{executablePath:process.env.STAM_CHROMIUM_PATH}:{}),headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1440,height:1000}}),errors=[];
 let page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));await page.goto(service.url);
 await page.waitForFunction(()=>document.querySelector('[aria-label="출항 준비 함선"] option[value="misc-hull-b"]'));
 await page.locator('#run-guide summary').click();assert.match(await page.locator('#run-guide').innerText(),/28상자\/168 SCU/);
 await page.locator('.ready-partner-open').click();await page.locator('.ready-briefing [data-partner="navigator"]').click();
 await page.locator('#flight-ready-settings > summary').click();
 await page.getByLabel('출항 준비 함선',{exact:true}).selectOption('misc-hull-b');
 const startId=data.locations.find(p=>p.name==='New Babbage').id;
 await page.getByLabel('출항 준비 지명 검색',{exact:true}).fill('New Babbage');
 await page.getByLabel('출항 준비 출발지',{exact:true}).selectOption(startId);
 await page.getByRole('button',{name:'이 설정으로 준비',exact:true}).click();
 const before=await page.evaluate(()=>localStorage.getItem('stam-log-account-settings-v1'));
 assert.equal(JSON.parse(before).partner,'navigator');assert.equal(JSON.parse(before).shipId,'misc-hull-b');
 const old=service;await page.close();await old.close();service=null;
 service=await startLogService({file,port:Number(new URL(old.origin).port)});
 assert.equal(service.origin,old.origin);assert.notEqual(service.token,old.token);
 assert.equal((await fetch(service.origin+'/api/status',{headers:{Authorization:'Bearer '+old.token}})).status,401);
 page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));await page.goto(service.url);
 await page.waitForFunction(()=>document.querySelector('#live-status')?.textContent.includes('실시간 감시 중'));
 await page.waitForFunction(()=>document.querySelector('.ready-ship-summary')?.textContent.includes('MISC Hull B'));
 assert.equal(await page.evaluate(()=>localStorage.getItem('stam-log-account-settings-v1')),before);
 assert.match(await page.locator('.ready-ship-summary').innerText(),/이전 설정 · 확인 필요/);
 assert.equal(await page.getByLabel('출항 준비 출발지',{exact:true}).inputValue(),startId);
 assert.equal(await page.locator('#flight-ready-action').innerText(),'계약 수신 대기');
 assert.equal(await page.evaluate(()=>localStorage.getItem('sfc-history')),null);
 assert.equal(await page.locator('canvas').count(),0);
 await page.locator('#run-guide summary').click();await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,sameOriginRestart:true,preferencesRestored:true,freshPairingRequired:true,oldSettingsNeedConfirmation:true,noFakeHistory:true,noIdleRenderer:true,guideMobileOverflow:false,errors}));
}finally{await browser?.close();await service?.close();await rm(dir,{recursive:true,force:true});}
